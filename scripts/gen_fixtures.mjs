// y-protocols sync messages. Replica A is plain Yjs; replica B is a Yjs
// document whose state MoonBit loads and then mirrors (same client id), so
// every message MoonBit produces must equal the one y-protocols produces.

const syncMessage = (f) => {
  const e = encoding.createEncoder()
  f(e)
  return encoding.toUint8Array(e)
}

const genProtocol = () => {
  const a = newDoc(31)
  a.getText('t').insert(0, 'from A 😀')
  a.getMap('m').set('a', 1)
  const b = newDoc(32, { gc: false })
  b.getText('t').insert(0, 'from B')
  b.getMap('m').set('b', [true])
  const bInitial = Y.encodeStateAsUpdate(b)

  const step1A = syncMessage(e => syncProtocol.writeSyncStep1(e, a))
  const step1B = syncMessage(e => syncProtocol.writeSyncStep1(e, b))
  // what B answers to A's SyncStep1, and what A answers to B's
  const replyB = syncMessage(e => syncProtocol.readSyncMessage(decoding.createDecoder(step1A), e, b, null))
  const replyA = syncMessage(e => syncProtocol.readSyncMessage(decoding.createDecoder(step1B), e, a, null))
  // B receives A's SyncStep2
  syncProtocol.readSyncMessage(decoding.createDecoder(replyA), encoding.createEncoder(), b, null)
  const bAfterSync = Y.encodeStateAsUpdate(b)
  // B edits; the update is broadcast as an Update message
  const bUpdates = []
  b.on('update', (u) => bUpdates.push(u))
  b.getText('t').insert(0, '>> ')
  const updateB = syncMessage(e => syncProtocol.writeUpdate(e, bUpdates[0]))
  // y-websocket frames: message kind 0 (sync) in front of the sync message
  const wsStep1B = syncMessage(e => { encoding.writeVarUint(e, 0); syncProtocol.writeSyncStep1(e, b) })
  const wsStep1A = syncMessage(e => { encoding.writeVarUint(e, 0); syncProtocol.writeSyncStep1(e, a) })
  const wsReplyB = syncMessage(e => {
    const d = decoding.createDecoder(wsStep1A)
    decoding.readVarUint(d)
    encoding.writeVarUint(e, 0)
    syncProtocol.readSyncMessage(d, e, b, null)
  })

  const json = {
    bInitial: hex(bInitial),
    step1A: hex(step1A),
    step1B: hex(step1B),
    replyB: hex(replyB),
    replyA: hex(replyA),
    bAfterSync: hex(bAfterSync),
    updateB: hex(updateB),
    bFinal: hex(Y.encodeStateAsUpdate(b)),
    wsStep1A: hex(wsStep1A),
    wsStep1B: hex(wsStep1B),
    wsReplyB: hex(wsReplyB)
  }
  let mbt = `\n///|\nlet b_client : UInt = 32\n`
  for (const [k, v] of Object.entries(json)) {
    mbt += `\n///|\nlet ${k.replace(/[A-Z]/g, c => '_' + c.toLowerCase())} : String = "${v}"\n`
  }
  writeFixture('protocol', 'protocol', json, mbt, HEADER(` / y-protocols@${Y_PROTOCOLS_VERSION}`))
}

